// Light by default even on a dark phone; one theme switch shared by the site and the app.
const { chromium } = require('playwright');
const path = require('path'), fs = require('fs');
const BASE = process.env.BASE || 'http://127.0.0.1:8766/';
const OUT = process.env.OUT || path.join(__dirname, '../.out/theme');
fs.mkdirSync(OUT, { recursive: true });
let fails = 0; const ok = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const b = await chromium.launch();
  for (const [w, h] of [[320, 700], [390, 844], [1440, 900]]) {
    const ctx = await b.newContext({ viewport: { width: w, height: h }, colorScheme: 'dark' });
    const page = await ctx.newPage();
    const errs = []; page.on('pageerror', (e) => errs.push(e.message));
    const theme = () => page.locator('html').getAttribute('data-theme');
    const pageColor = () => page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--page').trim().toUpperCase());
    await page.goto(BASE + 'index.html');
    ok(await theme() === 'light' && await pageColor() === '#FFFFFF', w + ': site starts light on a dark phone');
    const btn = page.locator('.s-nav [data-theme-toggle]');
    ok(await btn.isVisible(), w + ': theme switch visible in the header');
    const box = await btn.boundingBox();
    ok(box && box.x >= 0 && box.x + box.width <= w, w + ': switch fits the screen');
    const over = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
    ok(over <= 0, w + ': no sideways scroll, overflow ' + over);
    if (w !== 1440) await page.screenshot({ path: OUT + '/' + w + '-site-light.png' });
    await btn.click();
    ok(await theme() === 'dark' && await pageColor() === '#000000', w + ': switch turns the site dark');
    ok(await btn.getAttribute('aria-label') === 'Включить светлую тему', w + ': label now offers light');
    ok(await page.locator('meta[name="theme-color"]').first().getAttribute('content') === '#000000', w + ': browser bar follows');
    if (w !== 1440) await page.screenshot({ path: OUT + '/' + w + '-site-dark.png' });
    await page.goto(BASE + 'pricing.html');
    ok(await theme() === 'dark', w + ': choice kept on the next page');
    await page.goto(BASE + 'kk/index.html');
    ok(await theme() === 'dark', w + ': and on the Kazakh page');
    ok(await page.locator('.s-nav [data-theme-toggle]').getAttribute('aria-label') === 'Күндізгі көріністі қосу', w + ': Kazakh label');
    await page.goto(BASE + 'app.html#start');
    await page.waitForSelector('.onb');
    ok(await page.locator('.up').getAttribute('data-theme') === 'night', w + ': app opens dark after choosing dark on the site');
    const appBtn = page.locator('.onbtop .iconbtn');
    ok(await appBtn.isVisible(), w + ': switch on the first app screen');
    if (w === 390) await page.screenshot({ path: OUT + '/390-app-start-dark.png' });
    await appBtn.click();
    ok(await page.locator('.up').getAttribute('data-theme') === 'day', w + ': app switch turns it light');
    ok(await page.evaluate(() => localStorage.getItem('enter-theme')) === 'light', w + ': saved for the site too');
    if (w === 390) await page.screenshot({ path: OUT + '/390-app-start-light.png' });
    await page.locator('.onbform .btn').click();
    await page.waitForSelector('.hgrid');
    const topBtn = page.locator('.topacts .iconbtn[title]').first();
    ok(await topBtn.isVisible(), w + ': switch in the top bar of the home screen');
    await topBtn.click();
    ok(await page.locator('.up').getAttribute('data-theme') === 'night', w + ': top bar switch works');
    if (w !== 320) await page.screenshot({ path: OUT + '/' + w + '-app-home-dark.png' });
    await page.evaluate(() => { location.hash = 'profile'; });
    await page.waitForSelector('.pgrid');
    ok(await page.locator('.seg').nth(1).locator('button').nth(1).getAttribute('aria-pressed') === 'true', w + ': profile shows dark selected');
    await page.locator('.seg').nth(1).locator('button').nth(0).click();
    ok(await page.locator('.up').getAttribute('data-theme') === 'day', w + ': profile switch still works');
    await page.goto(BASE + 'index.html');
    ok(await theme() === 'light', w + ': site follows the app back to light');
    ok(!errs.length, w + ': no page errors ' + errs.join(' | '));
    await ctx.close();
  }
  await b.close();
  console.log(fails ? fails + ' FAILED' : 'ALL OK');
})().catch((e) => { console.error('CRASH', e.message.slice(0, 400)); process.exit(1); });
